#!/usr/bin/env python3
"""Score a produced .pa.yaml against an eval case's expectations.

    python scripts/run_eval.py OUTPUT.pa.yaml --case tests/evals/app-shell
    python scripts/run_eval.py                       # score the bundled references
    python scripts/run_eval.py --list

WHAT THIS IS, AND WHAT IT IS NOT
===============================================================================
This is a **scorer**, not an eval loop. It takes a `.pa.yaml` that already
exists and checks it against assertions that can be settled mechanically.

It does NOT produce that file. Producing it means giving a model the case's
`mockup.html` and asking for a conversion, and CI does not run a model. There
is deliberately no API-key step here and none in the workflow: a harness that
quietly needed a key would be an eval loop in name only, green whenever the key
was missing.

So the loop is manual and has three steps, documented in `docs/evals.md`:

    1. ask Claude to convert tests/evals/<case>/mockup.html
    2. save the answer  (e.g. /tmp/out.pa.yaml)
    3. python scripts/run_eval.py /tmp/out.pa.yaml --case tests/evals/<case>

What CI *can* do is the part that needs no model: run the scorer against the
three bundled example screens, which stand in for known-good output. That
proves the scorer works. It proves nothing about the skill -- the examples were
not generated by one. Bare `run_eval.py` is exactly that self-check.

WHY EXPECTATIONS ARE RANGES
===============================================================================
Two good conversions of the same mockup will not agree on control count: one
may draw a divider with a Rectangle, another may leave it out. Asserting an
exact count would score style, not correctness. Every count here is a range
wide enough to admit any reasonable reading of the mockup and narrow enough to
catch a model that dropped half the screen or padded it with filler.

KNOWN DEVIATIONS
===============================================================================
A case may name a `reference.output` -- a file in this repo that stands in for
a good answer. Where that reference is known to miss an assertion, the case
lists the check id under `reference.known_deviations` with a reason, and the
scorer reports XFAIL instead of FAIL. If a known deviation starts passing the
scorer reports XPASS and exits non-zero: the waiver has gone stale and should
be deleted. Deviations apply to reference runs only, never to a file you pass
on the command line.

Requires PyYAML. `jsonschema` is optional; without it the lint layer that maps
to Studio PA1001 cannot run, and lint assertions are reported as UNPROVEN
rather than passing.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

try:
    import yaml
except ImportError:  # pragma: no cover
    print("ERROR: PyYAML is not installed. Run: pip install pyyaml", file=sys.stderr)
    raise SystemExit(2)

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))

import pa_lint  # noqa: E402  (needs the sys.path line above)

EVALS_DIR = ROOT / "tests" / "evals"

# Canvas defaults, used when a case names no canvas. Sourced from the bundled
# examples' own geometry (top bar X 280 + Width 1086 = 1366; sidebar Height 768),
# same as references/layout-mapping.md. That this is also Power Apps' documented
# default for a tablet-format app is UNVERIFIED here.
DEFAULT_CANVAS_WIDTH = 1366
DEFAULT_CANVAS_HEIGHT = 768

PASS, FAIL, XFAIL, XPASS, UNPROVEN, SKIP = "PASS", "FAIL", "XFAIL", "XPASS", "UNPROVEN", "SKIP"
# UNPROVEN and SKIP are not failures. UNPROVEN means the evidence for a check
# could not be gathered (jsonschema missing); SKIP means the case did not ask
# for the check at all.
BAD_RESULTS = (FAIL, XPASS)

NUMERIC_RE = re.compile(r"^=\s*(-?\d+(?:\.\d+)?)\s*$")
COMMENT_RE = re.compile(r"(?<!\S)#(.*)$")


# ----------------------------------------------------------------------- results


class Row:
    """One scored assertion."""

    __slots__ = ("check", "result", "expected", "actual", "note")

    def __init__(self, check, result, expected="", actual="", note=""):
        self.check = check
        self.result = result
        self.expected = str(expected)
        self.actual = str(actual)
        self.note = note

    def as_dict(self):
        return {
            "check": self.check,
            "result": self.result,
            "expected": self.expected,
            "actual": self.actual,
            "note": self.note,
        }


class Scorer:
    """Collects rows and applies the case's known-deviation waivers."""

    def __init__(self, deviations=None):
        # {check id: reason}. Empty for a file passed on the command line.
        self.deviations = deviations or {}
        self.rows = []

    def add(self, check, ok, expected, actual, note=""):
        waiver = self.deviations.get(check)
        if waiver is None:
            result = PASS if ok else FAIL
        elif ok:
            result = XPASS
            note = f"known deviation no longer applies: {waiver}"
        else:
            result = XFAIL
            # Keep the detail, but never at the cost of the reason -- a waived row
            # that does not say why it is waived is the thing this guards against.
            note = f"known: {waiver}" + (f" [{note}]" if note else "")
        self.rows.append(Row(check, result, expected, actual, note))

    def add_raw(self, check, result, expected="", actual="", note=""):
        self.rows.append(Row(check, result, expected, actual, note))

    def tally(self):
        counts = {PASS: 0, FAIL: 0, XFAIL: 0, XPASS: 0, UNPROVEN: 0, SKIP: 0}
        for row in self.rows:
            counts[row.result] = counts.get(row.result, 0) + 1
        return counts

    @property
    def ok(self):
        return not any(row.result in BAD_RESULTS for row in self.rows)


# ------------------------------------------------------------------ case loading


class CaseError(Exception):
    """The case directory itself is wrong -- not a scoring failure."""


class Case:
    def __init__(self, directory: Path, data: dict):
        self.dir = directory
        self.data = data or {}
        self.name = self.data.get("case") or directory.name
        self.title = self.data.get("title") or self.name

    @property
    def canvas(self):
        canvas = self.data.get("canvas") or {}
        return (int(canvas.get("width", DEFAULT_CANVAS_WIDTH)),
                int(canvas.get("height", DEFAULT_CANVAS_HEIGHT)))

    @property
    def reference(self):
        """(path, {check: reason}) or (None, {})."""
        ref = self.data.get("reference") or {}
        target = ref.get("output")
        if not target:
            return None, {}
        path = (self.dir / target).resolve()
        deviations = {}
        for entry in ref.get("known_deviations") or []:
            if not isinstance(entry, dict) or not entry.get("check"):
                raise CaseError(
                    f"{self.dir.name}: every known_deviations entry needs a 'check' key")
            reason = (entry.get("reason") or "").strip()
            if not reason:
                raise CaseError(
                    f"{self.dir.name}: known deviation {entry['check']!r} has no reason. "
                    "A waiver without a stated reason is indistinguishable from a bug.")
            deviations[str(entry["check"])] = " ".join(reason.split())
        return path, deviations


def load_case(directory: Path) -> Case:
    directory = Path(directory)
    if not directory.is_dir():
        raise CaseError(f"no such case directory: {directory}")
    spec = directory / "expectations.yaml"
    if not spec.is_file():
        raise CaseError(f"{directory} has no expectations.yaml")
    try:
        data = yaml.safe_load(spec.read_text(encoding="utf-8-sig"))
    except yaml.YAMLError as exc:
        raise CaseError(f"{spec}: {exc}") from exc
    if not isinstance(data, dict):
        raise CaseError(f"{spec}: expected a mapping at the top level")
    case = Case(directory, data)
    # Validate the reference block now, not when a reference run happens to read
    # it -- a malformed waiver should be caught by any invocation, including the
    # ones that will not use it.
    case.reference
    return case


def discover_cases(base: Path = EVALS_DIR):
    if not base.is_dir():
        return []
    return [d for d in sorted(base.iterdir()) if (d / "expectations.yaml").is_file()]


# ------------------------------------------------------------- reading the output


class Output:
    """Everything the assertions need, read once off the produced file."""

    def __init__(self, path: Path):
        self.path = path
        self.text = path.read_text(encoding="utf-8-sig")
        self.lines = self.text.splitlines()
        self.parse_findings, self.root, self.document = pa_lint.parse_layer(
            self.text, self.lines)
        self.parsed = not self.parse_findings and self.root is not None
        self.controls = list(pa_lint.walk_controls(self.root)) if self.parsed else []
        self.screens = {}
        if self.parsed:
            for key, value in pa_lint.map_items(pa_lint.map_get(self.root, "Screens")):
                self.screens[pa_lint.scalar_of(key)] = value

    # -- properties ------------------------------------------------------------

    @staticmethod
    def prop(ctrl, name):
        for prop_name, _key, value in ctrl.properties:
            if prop_name == name:
                return pa_lint.scalar_of(value)
        return None

    @classmethod
    def number(cls, ctrl, name):
        """The property as a float, or None when absent or not a plain number.

        A formula like `=Parent.Width - 40` is legitimate but cannot be placed on
        the canvas without evaluating Power Fx, which this scorer never does.
        Those are counted and reported, never guessed at.
        """
        raw = cls.prop(ctrl, name)
        if raw is None:
            return None
        match = NUMERIC_RE.match(raw.strip())
        return float(match.group(1)) if match else None

    @classmethod
    def declared_not_numeric(cls, ctrl, name):
        return cls.prop(ctrl, name) is not None and cls.number(ctrl, name) is None

    def screen_height(self, screen_name, fallback):
        """A screen's own Height wins over the canvas height: a screen that scrolls
        says so with `Height:`, and its content is meant to run past the viewport."""
        node = self.screens.get(screen_name)
        if node is None:
            return fallback
        for key, value in pa_lint.map_items(pa_lint.map_get(node, "Properties")):
            if pa_lint.scalar_of(key) == "Height":
                match = NUMERIC_RE.match((pa_lint.scalar_of(value) or "").strip())
                if match:
                    return float(match.group(1))
        return fallback

    # -- derived views ---------------------------------------------------------

    def type_counts(self):
        """{base control type: count}. Versions are stripped -- a case asserts that a
        card grid has cards, not which Studio build stamped the version."""
        counts = {}
        for ctrl in self.controls:
            base = (ctrl.ctype or "<none>").split("@", 1)[0]
            counts[base] = counts.get(base, 0) + 1
        return counts

    def absolute_boxes(self, canvas_height):
        """[(ctrl, x, y, w, h, screen_height)] with child coordinates resolved
        against their ancestors. Only ManualLayout containers position children by
        X/Y, so only those offsets accumulate."""
        offsets = {(): (0.0, 0.0)}
        boxes = []
        for ctrl in self.controls:
            # ctrl.path ends with [..., "Children", <index>, <name>]; the parent
            # control's own path is everything before that tail.
            parent_key = tuple(ctrl.path[:-3])
            ox, oy = offsets.get(parent_key, (0.0, 0.0))
            x = self.number(ctrl, "X") or 0.0
            y = self.number(ctrl, "Y") or 0.0
            offsets[tuple(ctrl.path)] = (ox + x, oy + y)
            boxes.append((
                ctrl,
                ox + x,
                oy + y,
                self.number(ctrl, "Width"),
                self.number(ctrl, "Height"),
                self.screen_height(ctrl.screen, canvas_height),
            ))
        return boxes

    def unresolved_geometry(self):
        """Controls declaring a geometry property that is not a plain number."""
        out = []
        for ctrl in self.controls:
            for name in ("X", "Y", "Width", "Height"):
                if self.declared_not_numeric(ctrl, name):
                    out.append((ctrl, name, self.prop(ctrl, name)))
        return out

    def navigate_targets(self):
        """[(ctrl, property, target, commented)] for every Navigate() call."""
        out = []
        for ctrl in self.controls:
            for name, _key, value in ctrl.properties:
                text = pa_lint.scalar_of(value) or ""
                if "Navigate(" not in text:
                    continue
                for match in pa_lint.NAVIGATE_RE.finditer(text):
                    target = next(g for g in match.groups() if g)
                    commented = pa_lint._line_has_comment(self.lines, value)
                    out.append((ctrl, name, target, commented))
        return out

    def comments(self):
        """Every `#` comment in the file, as one lowercase blob.

        A .pa.yaml has nowhere else to carry a declaration: the prose the model
        writes in chat is not in the file, so a limitation the case asks about has
        to be stated in a comment to be checkable at all. docs/evals.md says so.
        """
        found = []
        for line in self.lines:
            stripped = line.strip()
            if stripped.startswith("#"):
                found.append(stripped[1:])
                continue
            match = COMMENT_RE.search(line)
            if match:
                found.append(match.group(1))
        return "\n".join(found).lower()

    def property_names(self):
        names = set()
        for ctrl in self.controls:
            for name, _key, _value in ctrl.properties:
                names.add(name)
        return names


# ------------------------------------------------------------------------ checks
#
# Every check id below is stable: a case's known_deviations names one, so
# renaming one silently un-waives a deviation.


def _range(spec, default_min=0, default_max=None):
    """A count constraint: {min: N, max: M}, a bare int (exact), or [min, max]."""
    if spec is None:
        return default_min, default_max
    if isinstance(spec, int):
        return spec, spec
    if isinstance(spec, (list, tuple)) and len(spec) == 2:
        return int(spec[0]), int(spec[1])
    if isinstance(spec, dict):
        low = spec.get("min", default_min)
        high = spec.get("max", default_max)
        return (default_min if low is None else int(low),
                None if high is None else int(high))
    raise CaseError(f"cannot read a count range from {spec!r}")


def _fmt_range(low, high):
    if high is None:
        return f">= {low}"
    if low == high:
        return str(low)
    return f"{low}-{high}"


def _in_range(value, low, high):
    return value >= low and (high is None or value <= high)


def check_structure(scorer, case, out):
    spec = case.data.get("structure")
    if spec is None:
        scorer.add_raw("structure.screens", SKIP, "-", "-", "case asserts nothing here")
        return
    low, high = _range(spec.get("screens"), 1, None)
    count = len(out.screens)
    scorer.add("structure.screens", _in_range(count, low, high),
               _fmt_range(low, high), count)

    required = spec.get("required_screen_properties") or []
    if required:
        missing = []
        for screen_name, node in out.screens.items():
            present = {pa_lint.scalar_of(k)
                       for k, _v in pa_lint.map_items(pa_lint.map_get(node, "Properties"))}
            for name in required:
                if name not in present:
                    missing.append(f"{screen_name}.{name}")
        scorer.add("structure.screen-properties", not missing,
                   "all present", ", ".join(missing) or "all present")


def check_lint(scorer, case, out, lint_report, schema_available):
    spec = case.data.get("lint")
    if spec is None:
        scorer.add_raw("lint.verdict", SKIP, "-", "-", "case asserts nothing here")
        return

    if lint_report is None:
        scorer.add_raw("lint.verdict", UNPROVEN, "-", "-", "the file did not parse")
        return

    accepted = spec.get("verdict")
    if accepted is not None:
        if isinstance(accepted, str):
            accepted = [accepted]
        accepted = [str(v) for v in accepted]
        actual = lint_report["verdict_code"]
        if not schema_available:
            # The layer that catches PA1001 did not run. pa_lint reports
            # "unproven" rather than "safe" for exactly this reason, and a
            # scorer that called that a pass would be laundering a missing
            # dependency into a green row.
            scorer.add_raw("lint.verdict", UNPROVEN, "/".join(accepted), actual,
                           "jsonschema is not installed -- install it to score this")
        else:
            scorer.add("lint.verdict", actual in accepted, "/".join(accepted), actual,
                       note="" if actual in accepted else lint_report["verdict"])

    _, max_errors = _range(spec.get("max_errors", 0), 0, 0)
    errors = lint_report["errors"]
    scorer.add("lint.errors", errors <= (max_errors or 0),
               f"<= {max_errors or 0}", errors)

    if "max_warnings" in spec:
        _, max_warnings = _range(spec.get("max_warnings"), 0, 0)
        warnings = lint_report["warnings"]
        scorer.add("lint.warnings", warnings <= (max_warnings or 0),
                   f"<= {max_warnings or 0}", warnings)

    budgets = spec.get("max_per_check") or {}
    if budgets:
        seen = {}
        for finding in lint_report["findings"]:
            seen[finding["check"]] = seen.get(finding["check"], 0) + 1
        for check_id, allowed in sorted(budgets.items()):
            _, high = _range(allowed, 0, 0)
            count = seen.get(check_id, 0)
            scorer.add(f"lint.max_per_check:{check_id}", count <= (high or 0),
                       f"<= {high or 0}", count)


def check_controls(scorer, case, out):
    spec = case.data.get("controls")
    if spec is None:
        scorer.add_raw("controls.total", SKIP, "-", "-", "case asserts nothing here")
        return
    counts = out.type_counts()
    total = len(out.controls)

    if "total" in spec:
        low, high = _range(spec.get("total"))
        scorer.add("controls.total", _in_range(total, low, high),
                   _fmt_range(low, high), total)

    for ctype in spec.get("required_types") or []:
        scorer.add(f"controls.required:{ctype}", counts.get(ctype, 0) > 0,
                   ">= 1", counts.get(ctype, 0))

    for ctype in spec.get("forbidden_types") or []:
        scorer.add(f"controls.forbidden:{ctype}", counts.get(ctype, 0) == 0,
                   "0", counts.get(ctype, 0))

    for ctype, allowed in sorted((spec.get("by_type") or {}).items()):
        low, high = _range(allowed)
        count = counts.get(ctype, 0)
        scorer.add(f"controls.by_type:{ctype}", _in_range(count, low, high),
                   _fmt_range(low, high), count)


def check_geometry(scorer, case, out):
    spec = case.data.get("geometry")
    if spec is None:
        scorer.add_raw("geometry.in-bounds", SKIP, "-", "-", "case asserts nothing here")
        return
    width, height = case.canvas

    if spec.get("in_bounds", True):
        offenders = []
        for ctrl, x, y, w, h, screen_h in out.absolute_boxes(height):
            problems = []
            if x < 0 or y < 0:
                problems.append(f"origin ({x:g},{y:g})")
            if w is not None and x + w > width:
                problems.append(f"right edge {x + w:g} > {width}")
            if h is not None and y + h > screen_h:
                problems.append(f"bottom edge {y + h:g} > {screen_h:g}")
            if problems:
                offenders.append(f"{ctrl.name}: {'; '.join(problems)}")
        scorer.add("geometry.in-bounds", not offenders,
                   f"all inside {width}x{height}",
                   f"{len(offenders)} outside" if offenders else "all inside",
                   note="; ".join(offenders[:4]))

    if "max_unresolved" in spec:
        _, high = _range(spec.get("max_unresolved"), 0, 0)
        unresolved = out.unresolved_geometry()
        scorer.add("geometry.unresolved", len(unresolved) <= (high or 0),
                   f"<= {high or 0}", len(unresolved),
                   note="; ".join(f"{c.name}.{n}={v}" for c, n, v in unresolved[:4]))


def check_navigation(scorer, case, out):
    spec = case.data.get("navigation")
    if spec is None:
        scorer.add_raw("navigation.targets-resolve", SKIP, "-", "-",
                       "case asserts nothing here")
        return

    calls = out.navigate_targets()
    if "count" in spec:
        low, high = _range(spec.get("count"))
        scorer.add("navigation.count", _in_range(len(calls), low, high),
                   _fmt_range(low, high), len(calls))

    if spec.get("targets_resolve", True):
        # "Resolves" means: a screen in this file, or an acknowledged placeholder.
        # SKILL.md rule 7 allows the second because a single-screen deliverable
        # cannot contain the screen it navigates to -- but it has to say so in a
        # comment, so the gap is visible rather than silent.
        unresolved = [f"{c.name}.{p} -> {t}"
                      for c, p, t, commented in calls
                      if t not in out.screens and not commented]
        scorer.add("navigation.targets-resolve", not unresolved,
                   "every target a screen here or a commented placeholder",
                   f"{len(unresolved)} dangling" if unresolved else "all resolve",
                   note="; ".join(unresolved[:4]))


def check_catalog(scorer, case, out, lint_report):
    spec = case.data.get("catalog")
    if spec is None:
        scorer.add_raw("catalog.untagged-unverified", SKIP, "-", "-",
                       "case asserts nothing here")
        return
    if lint_report is None:
        scorer.add_raw("catalog.untagged-unverified", UNPROVEN, "-", "-",
                       "the file did not parse")
        return

    if "max_untagged_unverified" in spec:
        _, high = _range(spec.get("max_untagged_unverified"), 0, 0)
        # pa_lint L3 already answers exactly this question -- "an unverified item
        # with no '# UNVERIFIED' comment" -- so it is reused rather than
        # reimplemented here, where the two could drift apart.
        offenders = [f for f in lint_report["findings"]
                     if f["check"] == "L3.missing-unverified-comment"]
        scorer.add("catalog.untagged-unverified", len(offenders) <= (high or 0),
                   f"<= {high or 0}", len(offenders),
                   note="; ".join(f["path"] for f in offenders[:4]))

    if "max_unverified_properties" in spec:
        _, high = _range(spec.get("max_unverified_properties"), 0, 0)
        offenders = [f for f in lint_report["findings"]
                     if f["check"] == "L2.unverified-property"]
        scorer.add("catalog.unverified-properties", len(offenders) <= (high or 0),
                   f"<= {high or 0}", len(offenders),
                   note="; ".join(f["path"] for f in offenders[:4]))


def check_limitations(scorer, case, out):
    """The honesty check: did the output declare what it could not do?

    A model that cannot reproduce `box-shadow` has two ways out. It can say so --
    in a comment, since that is the only channel a .pa.yaml has -- or it can
    invent a `Shadow:` property that Studio will reject. Those are the two things
    this check separates, and it is why the hard case exists.
    """
    spec = case.data.get("limitations")
    if spec is None:
        scorer.add_raw("limitations.declared", SKIP, "-", "-",
                       "case asserts nothing here")
        return

    blob = out.comments()
    for entry in spec.get("declared") or []:
        if not isinstance(entry, dict) or not entry.get("id"):
            raise CaseError("every limitations.declared entry needs an 'id'")
        patterns = entry.get("patterns") or [entry["id"]]
        hit = next((p for p in patterns
                    if re.search(p, blob, re.IGNORECASE)), None)
        scorer.add(f"limitations.declared:{entry['id']}", hit is not None,
                   "named in a comment",
                   f"matched /{hit}/" if hit else "not mentioned",
                   note="" if hit else f"tried: {', '.join(patterns)}")

    forbidden = spec.get("forbidden_properties") or []
    if forbidden:
        used = sorted(set(forbidden) & out.property_names())
        scorer.add("limitations.no-invented-property", not used,
                   "none of the invented names", ", ".join(used) or "none used")

    substitutes = spec.get("substitute_types") or []
    if substitutes:
        counts = out.type_counts()
        present = [t for t in substitutes if counts.get(t, 0) > 0]
        scorer.add("limitations.substitute-offered", bool(present),
                   " or ".join(substitutes), ", ".join(present) or "none present")


# ------------------------------------------------------------------- orchestration


def score(case: Case, output_path: Path, deviations=None):
    """Score one file against one case. Raises CaseError for a broken case;
    a file that will not parse is a FAIL row, not an exception."""
    scorer = Scorer(deviations)
    out = Output(output_path)

    scorer.add("output.parses", out.parsed, "parses as YAML",
               "yes" if out.parsed else "no",
               note="" if out.parsed else "; ".join(
                   f.message for f in out.parse_findings[:2]))

    if not out.parsed:
        # Everything downstream reads the parsed tree. Reporting each of those as
        # a separate failure would turn one bug into fifteen rows.
        for check in ("structure.screens", "lint.verdict", "controls.total",
                      "geometry.in-bounds", "navigation.targets-resolve",
                      "catalog.untagged-unverified"):
            scorer.add_raw(check, UNPROVEN, "-", "-", "the file did not parse")
        return scorer, out, None

    catalog = pa_lint.load_catalog(pa_lint.DEFAULT_CATALOG)
    candidates = pa_lint.load_candidates(pa_lint.DEFAULT_CANDIDATES)
    schema = None
    if pa_lint.HAVE_JSONSCHEMA:
        schema = yaml.safe_load(pa_lint.SCHEMA_PATH.read_text(encoding="utf-8-sig"))
    lint_report = pa_lint.lint_file(output_path, catalog, schema, candidates)

    check_structure(scorer, case, out)
    check_lint(scorer, case, out, lint_report, schema is not None)
    check_controls(scorer, case, out)
    check_geometry(scorer, case, out)
    check_navigation(scorer, case, out)
    check_catalog(scorer, case, out, lint_report)
    check_limitations(scorer, case, out)

    return scorer, out, lint_report


# -------------------------------------------------------------------- rendering


def render(case: Case, output_path: Path, scorer: Scorer, reference: bool) -> str:
    header = f"{case.name}  <-  {_rel(output_path)}"
    if reference:
        header += "   [reference output, not model-generated]"

    widths = [
        max(8, max((len(r.check) for r in scorer.rows), default=8)),
        max(8, max((len(r.expected) for r in scorer.rows), default=8)),
        max(6, max((len(r.actual) for r in scorer.rows), default=6)),
    ]
    rule = "-" * min(100, 10 + sum(widths) + 6)

    out = [rule, header, rule,
           f"{'RESULT':<9}{'CHECK':<{widths[0] + 2}}"
           f"{'EXPECTED':<{widths[1] + 2}}{'ACTUAL':<{widths[2] + 2}}"]
    out.append(rule)
    for row in scorer.rows:
        out.append(f"{row.result:<9}{row.check:<{widths[0] + 2}}"
                   f"{row.expected:<{widths[1] + 2}}{row.actual:<{widths[2] + 2}}")
        if row.note:
            out.append(f"{'':<9}  -> {row.note}")
    out.append(rule)

    counts = scorer.tally()
    parts = [f"{counts[PASS]} passed", f"{counts[FAIL]} failed"]
    for key, label in ((XFAIL, "known deviation"), (XPASS, "stale waiver"),
                       (UNPROVEN, "unproven"), (SKIP, "not asserted")):
        if counts.get(key):
            parts.append(f"{counts[key]} {label}")
    out.append(", ".join(parts))
    return "\n".join(out)


def _rel(path: Path) -> str:
    try:
        return path.resolve().relative_to(ROOT).as_posix()
    except ValueError:
        return path.as_posix()


# -------------------------------------------------------------------------- main


def run_one(case: Case, output_path: Path, deviations, reference, args, results):
    if not output_path.is_file():
        print(f"ERROR: no such output file: {output_path}", file=sys.stderr)
        return 2
    scorer, _out, lint_report = score(case, output_path, deviations)
    results.append({
        "case": case.name,
        "case_dir": _rel(case.dir),
        "output": _rel(output_path),
        "reference": reference,
        "ok": scorer.ok,
        "rows": [r.as_dict() for r in scorer.rows],
        "tally": scorer.tally(),
        "lint_verdict": lint_report["verdict_code"] if lint_report else None,
    })
    if not args.json:
        print(render(case, output_path, scorer, reference))
        print()
    return 0 if scorer.ok else 1


def main(argv=None):
    parser = argparse.ArgumentParser(
        prog="run_eval.py",
        description="Score a produced .pa.yaml against an eval case. This scores an "
                    "output that already exists; producing it needs a model, which "
                    "CI does not run. See docs/evals.md.",
    )
    parser.add_argument("output", nargs="?", type=Path,
                        help="the .pa.yaml to score. Omit to score every case that "
                             "names a reference output (the self-check CI runs).")
    parser.add_argument("--case", type=Path,
                        help="the case directory, e.g. tests/evals/app-shell")
    parser.add_argument("--evals-dir", type=Path, default=EVALS_DIR,
                        help="where the cases live (default: tests/evals)")
    parser.add_argument("--list", action="store_true",
                        help="list the available cases and exit")
    parser.add_argument("--json", action="store_true",
                        help="emit the scored rows as JSON")
    args = parser.parse_args(argv)

    if not args.json:
        try:
            sys.stdout.reconfigure(encoding="utf-8", errors="replace")
        except (AttributeError, ValueError):  # pragma: no cover
            pass

    case_dirs = discover_cases(args.evals_dir)

    if args.list:
        if not case_dirs:
            print(f"No cases under {_rel(args.evals_dir)}")
            return 1
        for directory in case_dirs:
            try:
                case = load_case(directory)
            except CaseError as exc:
                print(f"  {directory.name:<22} BROKEN: {exc}")
                continue
            ref, _ = case.reference
            marker = "  (has a reference output)" if ref else ""
            print(f"  {case.name:<22} {case.title}{marker}")
        return 0

    results = []
    exit_code = 0

    if args.output is not None:
        if args.case is None:
            parser.error("--case is required when you pass an output file")
        try:
            case = load_case(args.case)
        except CaseError as exc:
            print(f"ERROR: {exc}", file=sys.stderr)
            return 2
        # Waivers describe the bundled reference, not a file the user just made.
        # Applying them to a fresh output would hide a real regression.
        exit_code = run_one(case, args.output, {}, False, args, results)
    else:
        if args.case is not None:
            parser.error("pass an output file with --case, or neither")
        if not case_dirs:
            print(f"ERROR: no cases under {_rel(args.evals_dir)}", file=sys.stderr)
            return 2
        scored = 0
        for directory in case_dirs:
            try:
                case = load_case(directory)
                ref_path, deviations = case.reference
            except CaseError as exc:
                print(f"ERROR: {exc}", file=sys.stderr)
                return 2
            if ref_path is None:
                if not args.json:
                    print(f"{directory.name}: no reference output -- run this case by "
                          f"hand (see docs/evals.md)\n")
                continue
            scored += 1
            code = run_one(case, ref_path, deviations, True, args, results)
            if code == 2:
                return 2
            exit_code = exit_code or code
        if scored == 0:
            print("ERROR: no case names a reference output", file=sys.stderr)
            return 2
        if not args.json:
            failed = sum(1 for r in results if not r["ok"])
            print(f"SELF-CHECK: {scored} case(s) scored against bundled reference "
                  f"outputs, {failed} with unexpected results.")
            print("This exercises the scorer. It says nothing about the skill's "
                  "output quality -- the references were written by hand, not "
                  "generated. See docs/evals.md.")

    if args.json:
        print(json.dumps({
            "version": 1,
            "jsonschema_available": pa_lint.HAVE_JSONSCHEMA,
            "results": results,
            "summary": {
                "cases": len(results),
                "failed": sum(1 for r in results if not r["ok"]),
                "exit_code": exit_code,
            },
        }, indent=2))
    return exit_code


if __name__ == "__main__":
    raise SystemExit(main())
